/// The custom sidebars' `workspaces[i].agents` without stale sessions and with the agents on
/// `cmux ssh` hosts.
@MainActor
enum WheelhouseRemoteAgents {
    private static var roster = WheelhouseRemoteAgentRoster()
    /// Sessions the app restores at launch are stamped within its first seconds. Read once at
    /// launch, by `WheelhouseAgentsPanel.start`.
    static let restoredBefore = Date().addingTimeInterval(30)

    static func update(_ statuses: [UUID: [UUID: RemoteAgentSidebarStatus]]) {
        roster.update(statuses, now: Date())
    }

    static func merging(_ agents: [CustomSidebarAgentSnapshot], in workspace: Workspace) -> [CustomSidebarAgentSnapshot] {
        let agents = WheelhouseAgentListCleanup.removingStale(agents, restoredBefore: restoredBefore) { pid in
            kill(pid_t(pid), 0) == 0 || errno == EPERM
        }
        let rows = roster.rows(workspaceID: workspace.id)
        guard !rows.isEmpty else { return agents }
        var surfaceIdByPanelId: [UUID: UUID] = [:]
        for paneId in workspace.bonsplitController.allPaneIds {
            for tab in workspace.bonsplitController.tabs(inPane: paneId) {
                guard let panelId = workspace.panelIdFromSurfaceId(tab.id) else { continue }
                surfaceIdByPanelId[panelId] = tab.id.uuid
            }
        }
        let remote = rows.map { row in
            WheelhouseRemoteAgentState(
                panelId: row.panelID, kind: row.kind, name: row.kind == "claude" ? "Claude" : row.kind.capitalized,
                status: row.status, since: row.since)
        }
        return WheelhouseRemoteAgentMerge.merge(agents, remote: remote, surfaceIdByPanelId: surfaceIdByPanelId)
    }
}

/// The Agents panel: a custom sidebar that takes the right sidebar while a project is selected,
/// with the project's agents and its earlier sessions. Collapsed, it leaves an Agents button in
/// the title bar that opens it again.
@MainActor
enum WheelhouseAgentsPanel {
    static let panelName = "project-agents"
    private static let collapsedKey = "wheelhouse.agentsPanel.collapsed"
    private static let enabledKey = "wheelhouse.agentsPanel.enabled"
    private static let generatedHeader =
        "// Generated by Wheelhouse IDE from project-agents.js; changes here are overwritten.\n"

    private static var timer: Timer?
    /// The workspace the open panel was last shown for.
    private static var shownFor: UUID?
    private static var modeBefore: RightSidebarMode = .files
    private static var nameBefore: String?

    static func start() {
        guard timer == nil else { return }
        _ = WheelhouseRemoteAgents.restoredBefore
        installScripts()
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { _ in
            MainActor.assumeIsolated {
                WheelhouseSessions.tick()
                evaluate()
            }
        }
    }

    /// Whether the right sidebar's mode is the panel. It then shows nothing else: the bar of
    /// the other modes is left out.
    static func isShowing(_ state: FileExplorerState) -> Bool {
        state.mode == .customSidebar && state.customSidebarName == panelName
    }

    static func setCollapsed(_ collapsed: Bool) {
        UserDefaults.standard.set(collapsed, forKey: collapsedKey)
        if collapsed, let state = AppDelegate.shared?.fileExplorerState, showsPanel(state) {
            hide(state, close: true)
        }
        evaluate()
    }

    private static func showsPanel(_ state: FileExplorerState) -> Bool {
        state.isVisible && isShowing(state)
    }

    private static func hide(_ state: FileExplorerState, close: Bool) {
        if close { state.setVisible(false) }
        if let nameBefore { state.selectCustomSidebar(name: nameBefore) }
        state.mode = modeBefore
        shownFor = nil
    }

    private static func evaluate() {
        let defaults = UserDefaults.standard
        let button = WheelhouseAgentsButtonModel.shared
        guard defaults.object(forKey: enabledKey) as? Bool ?? true,
              let app = AppDelegate.shared, let state = app.fileExplorerState,
              let workspace = app.tabManager?.selectedWorkspace else {
            button.update(isVisible: false, waiting: 0, working: 0)
            return
        }
        let isProject = WheelhouseSessions.project(of: workspace) != nil
        let showing = showsPanel(state)
        if isProject {
            if showing {
                defaults.set(false, forKey: collapsedKey)
            } else if shownFor == workspace.id, !state.isVisible {
                // The right sidebar was hidden with the panel up: the panel is collapsed.
                defaults.set(true, forKey: collapsedKey)
            }
        }
        let collapsed = defaults.bool(forKey: collapsedKey)
        let shownBefore = shownFor != nil
        shownFor = isProject && showing ? workspace.id : nil

        switch WheelhouseAgentsPanelPolicy.action(
            isProject: isProject, panelShowing: showing, sidebarVisible: state.isVisible, collapsed: collapsed
        ) {
        case .none:
            break
        case .show:
            let mode = state.mode
            let name = state.customSidebarName
            // The app's own command: a sidebar shown in another order of steps stays unlaid out.
            guard case .ok = app.applyRightSidebarRemoteCommand(.setCustomSidebar(name: panelName, focus: false))
            else { break }
            modeBefore = mode == .customSidebar ? modeBefore : mode
            nameBefore = name == panelName ? nameBefore : name
            shownFor = workspace.id
        case .hide:
            // Opened by the user outside a project, the right sidebar stays open on what it showed before.
            hide(state, close: shownBefore)
        }

        guard isProject, collapsed, !state.isVisible else {
            button.update(isVisible: false, waiting: 0, working: 0)
            return
        }
        let agents = workspace.customSidebarWorkspaceSnapshot(index: 0, selectedId: workspace.id, unreadCount: 0).agents
        button.update(
            isVisible: true,
            waiting: agents.filter { $0.status == "needs_input" }.count,
            working: agents.filter { $0.status == "working" }.count)
    }

    /// Writes the bundled panel script where custom sidebars are read from, leaving alone a
    /// file of the same name that this app did not write, and removes the rail copy that
    /// earlier builds wrote.
    private static func installScripts() {
        guard let source = Bundle.main.resourceURL?.appendingPathComponent("sidebars/\(panelName).js"),
              let script = try? String(contentsOf: source, encoding: .utf8) else { return }
        let directory = CmuxExtensionSidebarSelection.customSidebarsDirectory
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appendingPathComponent("\(panelName).js", isDirectory: false)
        let text = generatedHeader + script
        let current = try? String(contentsOf: url, encoding: .utf8)
        if current == nil || (current?.hasPrefix(generatedHeader) == true && current != text) {
            try? text.write(to: url, atomically: true, encoding: .utf8)
        }
        let rail = directory.appendingPathComponent("\(panelName)-rail.js", isDirectory: false)
        if (try? String(contentsOf: rail, encoding: .utf8))?.hasPrefix(generatedHeader) == true {
            try? FileManager.default.removeItem(at: rail)
        }
    }
}

/// What the title bar's Agents button shows: it is there while the selected project's panel
/// is collapsed.
@MainActor
final class WheelhouseAgentsButtonModel: ObservableObject {
    static let shared = WheelhouseAgentsButtonModel()

    @Published private(set) var isVisible = false
    @Published private(set) var waiting = 0
    @Published private(set) var working = 0

    func update(isVisible: Bool, waiting: Int, working: Int) {
        if self.isVisible != isVisible { self.isVisible = isVisible }
        if self.waiting != waiting { self.waiting = waiting }
        if self.working != working { self.working = working }
    }
}

/// Opens the collapsed Agents panel. Its dot is orange while an agent of the project waits on
/// the user and blue while one works.
struct WheelhouseAgentsButton: View {
    @ObservedObject private var model = WheelhouseAgentsButtonModel.shared

    var body: some View {
        if model.isVisible {
            Button {
                WheelhouseAgentsPanel.setCollapsed(false)
            } label: {
                HStack(spacing: 6) {
                    Circle()
                        .fill(model.waiting > 0 ? Color.orange : model.working > 0 ? Color.blue : Color.secondary.opacity(0.6))
                        .frame(width: 7, height: 7)
                    Text(String(localized: "wheelhouse.agentsButton.title", defaultValue: "Agents"))
                        .font(.system(size: 12, weight: .medium))
                    if model.waiting > 0 {
                        Text(verbatim: String(model.waiting))
                            .font(.system(size: 11, weight: .semibold))
                            .foregroundStyle(Color.orange)
                    }
                }
                .padding(.horizontal, 10)
                .padding(.vertical, 4)
                .background(Color.primary.opacity(0.08), in: Capsule())
                .contentShape(Capsule())
            }
            .buttonStyle(.plain)
            .help(String(localized: "wheelhouse.agentsButton.help", defaultValue: "Show this project's agents and earlier sessions"))
            .padding(.trailing, 10)
        }
    }
}

/// Every project's agent sessions, kept after they end: `<home>/sessions/<project>.json`, one
/// file per project file. A session is whatever agent the app sees running in one of the
/// project's terminals, so any harness the app can tell apart is recorded.
@MainActor
enum WheelhouseSessions {
    /// How many earlier sessions a sidebar is given per project.
    private static let listed = 30
    private static let launchedAt = Date()

    private static var ticks = 0
    /// Project name → the project file's name without its extension.
    private static var projects: [String: String] = [:]
    private static var histories: [String: WheelhouseSessionHistory] = [:]
    /// The harness a project file names for its agents, and the one for every project.
    private static var ownHarness: [String: String] = [:]
    private static var everyProjectHarness: String?
    /// When each project's memory was last written; none while it holds no notes.
    private static var memoryWrittenAt: [String: Double] = [:]
    /// The tab each running session of a project is in, by the record's id.
    private static var panels: [String: [String: UUID]] = [:]

    static var home: URL {
        if let home = ProcessInfo.processInfo.environment["WHEELHOUSE_HOME"], !home.isEmpty {
            return URL(fileURLWithPath: (home as NSString).expandingTildeInPath, isDirectory: true)
        }
        return FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent(".config/wheelhouse", isDirectory: true)
    }

    static func project(of workspace: Workspace) -> String? {
        projects[workspace.customTitle ?? workspace.title]
    }

    static func list(for workspace: Workspace) -> WheelhouseSessionList {
        guard let project = project(of: workspace) else { return .empty }
        let history = history(project)
        return WheelhouseSessionList(
            project: project, records: history.earlier(limit: listed), agent: agent(of: project, in: workspace, history: history))
    }

    /// The harness the project's agents are started on.
    static func harnessToStart(for project: String) -> WheelhouseHarness? {
        WheelhouseHarness.toStart(
            project: ownHarness[project], everyProject: everyProjectHarness, from: WheelhouseHarnessScan.all)
    }

    static func memoryFile(_ project: String) -> URL {
        home.appendingPathComponent("memory", isDirectory: true).appendingPathComponent("\(project).md")
    }

    /// The tab a running session of a project is in, when it runs on this Mac.
    static func panel(ofRecord id: String, project: String) -> UUID? {
        panels[project]?[id]
    }

    /// The tab of `workspace` a running session of its project is in, on this Mac or on a host.
    static func panel(of record: WheelhouseSessionRecord, project: String, in workspace: Workspace) -> UUID? {
        let panel = panels[project]?[record.id]
            ?? record.sessionId.flatMap { WheelhouseRemoteSessionScan.panel(ofSession: $0, in: workspace) }
        return panel.flatMap { workspace.panels[$0] == nil ? nil : $0 }
    }

    static func projectAgentSessions(of project: String) -> (running: WheelhouseSessionRecord?, last: WheelhouseSessionRecord?) {
        history(project).projectAgent
    }

    private static func agent(of project: String, in workspace: Workspace, history: WheelhouseSessionHistory) -> WheelhouseProjectAgent {
        let own = history.projectAgent
        var memoryPath = memoryFile(project).path
        var writtenAt = memoryWrittenAt[project]
        if workspace.remoteDisplayTarget != nil {
            // A project on a host keeps its memory there.
            let memory = WheelhouseRemoteSessionScan.memory(of: project, in: workspace)
            memoryPath = memory.path
            writtenAt = memory.file.flatMap { $0.hasNotes ? $0.modifiedAt : nil }
        }
        return WheelhouseProjectAgent(
            harness: harnessToStart(for: project),
            harnesses: WheelhouseHarnessScan.all.filter { $0.start?.contains("{prompt}") == true },
            hasOwnHarness: ownHarness[project] != nil,
            running: own.running, runningPanel: own.running.flatMap { panel(of: $0, project: project, in: workspace) },
            last: own.last, memoryPath: memoryPath, memoryWrittenAt: writtenAt,
            unavailable: WheelhouseProjectAgents.hostRefusal(in: workspace))
    }

    static func tick() {
        ticks += 1
        if ticks % 5 == 1 {
            readProjects()
            WheelhouseHarnessScan.readHarnesses(home: home)
        }
        if !projects.isEmpty, let manager = AppDelegate.shared?.tabManager {
            WheelhouseRemoteSessionScan.refresh(
                workspaces: manager.tabs.filter { project(of: $0) != nil }, harnesses: WheelhouseHarnessScan.all)
        }
        if ticks % 3 == 0 { record() }
    }

    /// Resumes a session in its project, or goes to it while it is running. With `copyLink`,
    /// puts the session's link on the pasteboard instead.
    @discardableResult
    static func open(project: String, id: String, copyLink: Bool = false) -> Bool {
        readProjects()
        guard projects.values.contains(project), let record = history(project).record(id: id) else { return false }
        if copyLink {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setString(WheelhouseSessionLink.string(project: project, id: id), forType: .string)
            return true
        }
        if let workspace = workspace(of: project) {
            show(record, in: workspace)
            return true
        }
        Task { @MainActor in
            _ = await WheelhouseProjects.run(["open", project], home: home.path)
            if let workspace = workspace(of: project) { show(record, in: workspace) }
        }
        return true
    }

    static func open(_ url: URL) -> Bool {
        guard let link = WheelhouseSessionLink.parse(url) else { return false }
        NSApp.activate()
        return open(project: link.project, id: link.id)
    }

    private static func workspace(of project: String) -> Workspace? {
        AppDelegate.shared?.tabManager?.tabs.first { self.project(of: $0) == project }
    }

    private static func show(_ record: WheelhouseSessionRecord, in workspace: Workspace) {
        AppDelegate.shared?.tabManager?.selectWorkspace(workspace)
        if record.endedAt == nil {
            let agents = workspace.customSidebarWorkspaceSnapshot(index: 0, selectedId: workspace.id, unreadCount: 0).agents
            if let panel = agents.first(where: { $0.sessionId == record.sessionId })?.panelId
                ?? project(of: workspace).flatMap({ panels[$0]?[record.id] })
                ?? record.sessionId.flatMap({ WheelhouseRemoteSessionScan.panel(ofSession: $0, in: workspace) }) {
                workspace.focusPanel(panel)
            }
            return
        }
        guard let resume = record.resume else { return }
        if let host = record.host {
            // A session on a host is opened again there: a new terminal next to one of the
            // workspace's own, started with the resume command. Typing into a new tab is not
            // a way in, because a host's terminal takes its command when it is created.
            guard workspace.remoteDisplayTarget == host else { return }
            _ = WheelhouseRemoteSessionScan.openTerminal(
                in: workspace,
                running: WheelhouseRemoteSessionProbe.resumeArguments(resume: resume, directory: record.directory))
            return
        }
        guard let pane = workspace.bonsplitController.focusedPaneId ?? workspace.bonsplitController.allPaneIds.first
        else { return }
        var directory = record.directory
        if let path = directory, !FileManager.default.fileExists(atPath: path) { directory = nil }
        _ = workspace.newTerminalSurface(inPane: pane, focus: true, workingDirectory: directory, initialInput: resume + "\n")
    }

    private static func readProjects() {
        let folder = home.appendingPathComponent("projects", isDirectory: true)
        let files = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)) ?? []
        var found: [String: String] = [:]
        var harnesses: [String: String] = [:]
        var written: [String: Double] = [:]
        for file in files where file.pathExtension == "yaml" && !file.lastPathComponent.hasPrefix("_") {
            guard let text = try? String(contentsOf: file, encoding: .utf8),
                  let name = WheelhouseProjectFile.name(in: text) else { continue }
            let project = file.deletingPathExtension().lastPathComponent
            found[name] = project
            harnesses[project] = WheelhouseProjectFile.value(of: "harness", in: text)
            let memory = memoryFile(project)
            if let notes = try? String(contentsOf: memory, encoding: .utf8), WheelhouseProjectAgent.hasNotes(memory: notes),
               let date = (try? FileManager.default.attributesOfItem(atPath: memory.path))?[.modificationDate] as? Date {
                written[project] = date.timeIntervalSince1970
            }
        }
        projects = found
        ownHarness = harnesses
        memoryWrittenAt = written
        everyProjectHarness = (try? String(contentsOf: home.appendingPathComponent("config.yaml"), encoding: .utf8))
            .flatMap { WheelhouseProjectFile.value(of: "harness", in: $0) }
        // A project taken off the board takes its sessions along; a later one of the same
        // name starts without them.
        let kept = Set(found.values)
        histories = histories.filter { kept.contains($0.key) }
    }

    private static func file(_ project: String) -> URL {
        home.appendingPathComponent("sessions", isDirectory: true).appendingPathComponent("\(project).json")
    }

    private static func history(_ project: String) -> WheelhouseSessionHistory {
        if let history = histories[project] { return history }
        let history = (try? Data(contentsOf: file(project))).map(WheelhouseSessionHistory.init(data:))
            ?? WheelhouseSessionHistory()
        histories[project] = history
        return history
    }

    private static func record() {
        guard !projects.isEmpty, let manager = AppDelegate.shared?.tabManager else { return }
        let now = Date()
        let index = SharedLiveAgentIndex.shared.currentIndexSchedulingRefresh()
        // Sessions restored at launch take a moment to show up again.
        let complete = now.timeIntervalSince(launchedAt) > 20
        var live: [String: [WheelhouseSessionObservation]] = [:]
        var tabs: [String: [String: UUID]] = [:]
        // Projects whose host has not said yet which of its sessions are running.
        var unsettled: Set<String> = []
        for workspace in manager.tabs {
            guard let project = project(of: workspace) else { continue }
            let observed = observations(in: workspace, index: index)
            live[project, default: []] += observed.sessions
            tabs[project, default: [:]].merge(observed.panels) { _, new in new }
            if !observed.isComplete { unsettled.insert(project) }
        }
        panels = tabs
        WheelhouseProjectAgents.forget(tabsNotIn: manager.tabs.flatMap { $0.panels.keys })
        for project in Set(projects.values) {
            var history = history(project)
            guard history.observe(
                live[project] ?? [], now: now.timeIntervalSince1970, complete: complete && !unsettled.contains(project)
            ) else {
                histories[project] = history
                continue
            }
            histories[project] = history
            let url = file(project)
            try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try? history.encoded().write(to: url, options: .atomic)
        }
    }

    /// The sessions running in a workspace. `isComplete` is false while a session that is
    /// not listed may still be running: its host has not answered, or not lately.
    private static func observations(
        in workspace: Workspace, index: RestorableAgentSessionIndex?
    ) -> (sessions: [WheelhouseSessionObservation], isComplete: Bool, panels: [String: UUID]) {
        let host = workspace.remoteDisplayTarget
        if host != nil {
            // The host knows its sessions' ids, which the app's own view of a remote terminal lacks.
            switch WheelhouseRemoteSessionScan.answer(for: workspace) {
            case .pending:
                return ([], false, [:])
            case .sessions(let sessions, let isCurrent):
                let observed = sessions.map { session in
                    WheelhouseSessionObservation(
                        id: session.id, kind: session.harness.id, name: session.harness.name, sessionId: session.id,
                        title: session.title, host: host, directory: session.directory,
                        resume: session.harness.resumeCommand(id: session.id),
                        role: session.role == WheelhouseProjectAgent.role ? session.role : nil,
                        transcript: session.transcript)
                }
                return (observed, isCurrent, [:])
            case .unavailable:
                break
            }
        }
        var found: [WheelhouseSessionObservation] = []
        var position: [String: Int] = [:]
        var tabs: [String: UUID] = [:]
        let agents = workspace.customSidebarWorkspaceSnapshot(index: 0, selectedId: nil, unreadCount: 0).agents
        for agent in agents where agent.status != "ended" && !agent.sessionId.hasPrefix("pending-") {
            if agent.sessionId.hasPrefix("remote:") {
                found.append(WheelhouseSessionObservation(
                    id: agent.sessionId, kind: agent.kind, name: agent.name, title: agent.title, host: host))
                continue
            }
            let indexed = agent.panelId
                .flatMap { index?.entry(workspaceId: workspace.id, panelId: $0)?.snapshot }
                .flatMap { $0.sessionId == agent.sessionId ? $0 : nil }
            let harness = WheelhouseHarnessScan.harness(id: agent.kind)
            position[agent.sessionId] = found.count
            tabs[agent.sessionId] = agent.panelId
            found.append(WheelhouseSessionObservation(
                id: agent.sessionId, kind: agent.kind,
                name: harness?.name ?? indexed?.registration?.name ?? indexed?.kind.displayName ?? agent.name,
                sessionId: agent.sessionId,
                title: agent.title ?? WheelhouseHarnessScan.title(transcript: agent.transcriptPath, session: agent.sessionId),
                host: host, directory: agent.workingDirectory ?? indexed?.workingDirectory,
                resume: host != nil ? nil : harness?.resumeCommand(id: agent.sessionId)
                    ?? resumeCommand(kind: agent.kind, sessionId: agent.sessionId, registration: indexed?.registration),
                transcript: host != nil ? nil : agent.transcriptPath))
        }
        guard host == nil else { return (found, true, [:]) }
        var terminals: [UUID] = []
        for pane in workspace.bonsplitController.allPaneIds {
            for tab in workspace.bonsplitController.tabs(inPane: pane) {
                if let panel = workspace.panelIdFromSurfaceId(tab.id) { terminals.append(panel) }
            }
        }
        // What the terminals' own processes say: any listed harness, and under which launcher.
        for panel in terminals {
            guard let tty = workspace.surfaceTTYNames[panel] else { continue }
            for session in WheelhouseHarnessScan.sessions(onTTY: tty) {
                let seen = position[session.id].map { found[$0] }
                let observation = WheelhouseSessionObservation(
                    id: session.id, kind: session.harness.id, name: session.harness.name, sessionId: session.id,
                    title: seen?.title ?? session.title, directory: seen?.directory ?? session.directory,
                    resume: session.harness.resumeCommand(id: session.id) ?? seen?.resume,
                    transcript: seen?.transcript ?? session.transcript)
                tabs[session.id] = panel
                if let index = position[session.id] {
                    found[index] = observation
                } else {
                    position[session.id] = found.count
                    found.append(observation)
                }
            }
        }
        // Agents only cmux can tell apart.
        for panel in terminals {
            guard let entry = index?.exactEntry(workspaceId: workspace.id, panelId: panel),
                  entry.processLiveness == .running, position[entry.snapshot.sessionId] == nil else { continue }
            let snapshot = entry.snapshot
            position[snapshot.sessionId] = found.count
            tabs[snapshot.sessionId] = panel
            found.append(WheelhouseSessionObservation(
                id: snapshot.sessionId, kind: snapshot.kind.rawValue,
                name: snapshot.registration?.name ?? snapshot.kind.displayName, sessionId: snapshot.sessionId,
                directory: snapshot.workingDirectory,
                resume: resumeCommand(
                    kind: snapshot.kind.rawValue, sessionId: snapshot.sessionId, registration: snapshot.registration)))
        }
        // A session in the tab the project agent was started in is the project agent's.
        for index in found.indices {
            guard let panel = tabs[found[index].id], WheelhouseProjectAgents.isProjectAgent(panel, session: found[index].id)
            else { continue }
            found[index].role = WheelhouseProjectAgent.role
        }
        return (found, true, tabs)
    }

    /// The harness's own way back into a session, from its kind and session id alone: the
    /// command line an agent was started with can hold credentials and is never kept.
    private static func resumeCommand(kind: String, sessionId: String, registration: CmuxVaultAgentRegistration?) -> String? {
        guard let kind = RestorableAgentKind(rawValue: kind) else { return nil }
        return SessionRestorableAgentSnapshot(
            kind: kind, sessionId: sessionId, workingDirectory: nil, launchCommand: nil, registration: registration
        ).resumeCommand(includeWorkingDirectoryPrefix: false)
    }
}

/// Starts a project's agents from the Agents panel: the project's own agent, which keeps the
/// project's memory, and any other agent, which is given the brief and the memory to read.
/// Each is the harness's ordinary session in the project's folder, in a new tab, whose first
/// message names the brief `proj brief` has just written.
@MainActor
enum WheelhouseProjectAgents {
    enum Role: String {
        case project
        case agent
    }

    /// Why no agent can be started in `workspace` on its host yet, in the user's words; nil on
    /// this Mac and once the host has answered.
    static func hostRefusal(in workspace: Workspace) -> String? {
        guard let host = workspace.remoteDisplayTarget else { return nil }
        if WheelhouseRemoteSessionScan.isUnreachable(workspace) {
            return String(
                localized: "wheelhouse.projectAgent.hostUnreachable",
                defaultValue: "Agents cannot be started on \(host) from here: Wheelhouse cannot reach it over ssh or run python3 there.")
        }
        guard WheelhouseRemoteSessionScan.home(for: workspace) != nil else {
            return String(
                localized: "wheelhouse.projectAgent.hostPending",
                defaultValue: "Waiting for \(host) to answer…")
        }
        return nil
    }

    /// The tabs the project agent was started in, and the session found in each.
    private static var started: [UUID: String?] = [:]

    static func isProjectAgent(_ panel: UUID, session: String) -> Bool {
        guard let known = started[panel] else { return false }
        if let known { return known == session }
        started[panel] = session
        return true
    }

    static func forget(tabsNotIn open: [UUID]) {
        guard !started.isEmpty else { return }
        let open = Set(open)
        started = started.filter { open.contains($0.key) }
    }

    /// Starts an agent in `workspace`'s project, or goes to the project agent when it runs.
    /// With `update`, the project agent is asked to bring the memory up to date. Returns why
    /// nothing was started, in the user's words.
    @discardableResult
    static func start(in workspace: Workspace, role: Role, harness id: String? = nil, update: Bool = false) -> String? {
        guard let project = WheelhouseSessions.project(of: workspace) else {
            return String(localized: "wheelhouse.projectAgent.noProject", defaultValue: "This workspace is not a project on the board.")
        }
        if let refusal = hostRefusal(in: workspace) { return refusal }
        let running = role == .project
            ? WheelhouseSessions.projectAgentSessions(of: project).running
                .flatMap { WheelhouseSessions.panel(of: $0, project: project, in: workspace) }
            : nil
        if let running, !update {
            workspace.focusPanel(running)
            return nil
        }
        let harness = id.flatMap { id in WheelhouseHarnessScan.all.first { $0.id == id } }
            ?? WheelhouseSessions.harnessToStart(for: project)
        guard let harness, harness.start != nil else {
            return String(
                localized: "wheelhouse.projectAgent.noHarness",
                defaultValue: "No harness has a start command. Give one a \"start\" line in harnesses.json.")
        }
        Task { @MainActor in
            guard let fields = await brief(project, in: workspace), let brief = fields["brief"] else { return }
            if let running {
                workspace.focusPanel(running)
                // The text and Return are sent apart: an agent's editor takes a carriage
                // return that arrives with pasted text as a line break.
                guard let terminal = workspace.terminalPanel(for: running),
                      terminal.sendText(WheelhouseProjectAgent.Prompt.update(brief: brief)) else { return }
                try? await Task.sleep(nanoseconds: 300_000_000)
                _ = terminal.sendNamedKey("enter")
                return
            }
            let name = fields["name"] ?? project
            let prompt = role == .project
                ? WheelhouseProjectAgent.Prompt.projectAgent(name: name, brief: brief)
                : WheelhouseProjectAgent.Prompt.agent(name: name, brief: brief)
            guard let command = harness.startCommand(prompt: prompt) else { return }
            var directory = fields["dir"].flatMap { $0.isEmpty ? nil : $0 }
            if workspace.remoteDisplayTarget != nil {
                // On a host the role travels with the agent, so the host can tell it apart.
                var opened: UUID?
                guard WheelhouseRemoteSessionScan.openTerminal(
                    in: workspace,
                    running: WheelhouseRemoteSessionProbe.startArguments(
                        start: command, directory: directory, role: role == .project ? WheelhouseProjectAgent.role : nil),
                    opened: { opened = $0 })
                else {
                    show(failure: String(
                        localized: "wheelhouse.projectAgent.noHostTerminal",
                        defaultValue: "The workspace has no terminal on its host to open a new one next to."))
                    return
                }
                guard role == .project, let panel = opened else { return }
                // The tab is named once the host has made the terminal, whose own name would
                // replace an earlier one.
                for _ in 0..<80 {
                    guard workspace.panels[panel] != nil else { return }
                    if SurfaceCatalog.shared.projectionIncludingPendingRestore(forPanel: panel)?.resource != nil { break }
                    try? await Task.sleep(nanoseconds: 250_000_000)
                }
                try? await Task.sleep(nanoseconds: 500_000_000)
                workspace.setPanelCustomTitle(
                    panelId: panel, title: String(localized: "wheelhouse.projectAgent.tab", defaultValue: "Project agent"))
                return
            }
            guard let pane = workspace.bonsplitController.focusedPaneId ?? workspace.bonsplitController.allPaneIds.first
            else { return }
            if let path = directory, !FileManager.default.fileExists(atPath: path) { directory = nil }
            guard let panel = workspace.newTerminalSurface(
                inPane: pane, focus: true, workingDirectory: directory, initialInput: command + "\n"
            ) else { return }
            if role == .project {
                started[panel.id] = .some(nil)
                workspace.setPanelCustomTitle(
                    panelId: panel.id,
                    title: String(localized: "wheelhouse.projectAgent.tab", defaultValue: "Project agent"))
            }
        }
        return nil
    }

    /// Opens the project's memory as an editor tab, creating the file first when it is missing.
    @discardableResult
    static func openMemory(in workspace: Workspace) -> Bool {
        guard let project = WheelhouseSessions.project(of: workspace) else { return false }
        if workspace.remoteDisplayTarget != nil {
            if let refusal = hostRefusal(in: workspace) {
                show(failure: refusal, title: String(
                    localized: "wheelhouse.projectAgent.memoryNotOpened", defaultValue: "The project memory was not opened."))
                return true
            }
            Task { @MainActor in
                var memory = WheelhouseRemoteSessionScan.memory(of: project, in: workspace)
                if memory.file == nil {
                    guard let fields = await brief(project, in: workspace), let path = fields["memory"] else { return }
                    memory.path = path
                }
                guard let pane = workspace.bonsplitController.focusedPaneId ?? workspace.bonsplitController.allPaneIds.first
                else { return }
                if !(await workspace.openRemoteFileInEditor(memory.path, inPane: pane, isCurrent: { true })) {
                    show(failure: String(
                        localized: "wheelhouse.projectAgent.memoryNeedsEditor",
                        defaultValue: "A file on a host opens in the editor, which is off or cannot open it."),
                        title: String(
                            localized: "wheelhouse.projectAgent.memoryNotOpened", defaultValue: "The project memory was not opened."))
                }
            }
            return true
        }
        Task { @MainActor in
            let path = WheelhouseSessions.memoryFile(project).path
            if !FileManager.default.fileExists(atPath: path) {
                let outcome = await WheelhouseProjects.run(["brief", project], home: WheelhouseSessions.home.path)
                guard outcome.succeeded else {
                    show(failure: outcome.message)
                    return
                }
            }
            guard let pane = workspace.bonsplitController.focusedPaneId ?? workspace.bonsplitController.allPaneIds.first
            else { return }
            _ = workspace.openFilePreviewSurfaces(inPane: pane, filePaths: [path], focus: true, reuseExisting: true)
        }
        return true
    }

    /// Writes the project's brief where its agents read it and makes sure its memory exists
    /// there: on this Mac, or on the workspace's host, where the brief is copied to. Returns
    /// what `proj brief` printed, with the paths agents use; nil after showing why not.
    private static func brief(_ project: String, in workspace: Workspace) async -> [String: String]? {
        var arguments = ["brief", project]
        let onHost = workspace.remoteDisplayTarget != nil
        if onHost {
            guard let home = WheelhouseRemoteSessionScan.home(for: workspace) else {
                show(failure: hostRefusal(in: workspace) ?? "")
                return nil
            }
            arguments += ["--remote-home", home]
            if let file = WheelhouseRemoteSessionScan.memory(of: project, in: workspace).file, file.hasNotes {
                arguments += ["--since", String(Int(file.modifiedAt))]
            }
        }
        let outcome = await WheelhouseProjects.run(arguments, home: WheelhouseSessions.home.path)
        let fields = briefFields(outcome.output)
        guard outcome.succeeded, fields["brief"] != nil else {
            show(failure: outcome.message)
            return nil
        }
        guard onHost else { return fields }
        guard let brief = fields["brief"], let memory = fields["memory"], let file = fields["file"],
              let template = fields["template"].flatMap({ Data(base64Encoded: $0) }),
              let text = try? Data(contentsOf: URL(fileURLWithPath: file)) else {
            show(failure: outcome.message)
            return nil
        }
        guard await WheelhouseRemoteSessionScan.copy(brief: text, to: brief, memory: memory, template: template, in: workspace)
        else {
            show(failure: String(
                localized: "wheelhouse.projectAgent.copyFailed",
                defaultValue: "The brief could not be copied to \(workspace.remoteDisplayTarget ?? "the host")."))
            return nil
        }
        return fields
    }

    /// What `proj brief` printed: a name and a value per line, with a tab between them.
    private static func briefFields(_ output: String) -> [String: String] {
        var fields: [String: String] = [:]
        for line in output.split(separator: "\n") {
            let parts = line.split(separator: "\t", maxSplits: 1, omittingEmptySubsequences: false)
            if parts.count == 2 { fields[String(parts[0])] = String(parts[1]) }
        }
        return fields
    }

    private static func show(failure message: String, title: String? = nil) {
        let alert = NSAlert()
        alert.alertStyle = .warning
        alert.messageText = title ?? String(
            localized: "wheelhouse.projectAgent.failed", defaultValue: "The agent was not started.")
        alert.informativeText = message
        if let window = NSApp.keyWindow ?? NSApp.mainWindow {
            alert.beginSheetModal(for: window) { _ in }
        } else {
            alert.runModal()
        }
    }
}

/// The agent sessions in the terminals of SSH hosts, as each host lists them when asked
/// (`WheelhouseRemoteSessionProbe`). A host is asked every few seconds while a project's
/// workspace is connected to it, off the main thread, one question at a time.
@MainActor
enum WheelhouseRemoteSessionScan {
    enum Answer {
        /// The host was asked and has not answered yet.
        case pending
        /// The host cannot be asked this way: no `python3`, no `/proc`, no connection so far.
        case unavailable
        /// The sessions in the workspace's terminals. `isCurrent` is false when the host did
        /// not answer the last time, so the list may have gone stale.
        case sessions([WheelhouseRemoteSession], isCurrent: Bool)
    }

    private struct Host {
        /// The last answer; nil before the first one.
        var sessions: [WheelhouseRemoteSession]?
        /// The user's home folder there, and the project memories found, from the last answer.
        var home: String?
        var files: [String: WheelhouseRemoteFile] = [:]
        var isCurrent = false
        var hasFailed = false
        var askedAt = Date.distantPast
        var isAsking = false
    }

    private static let interval: TimeInterval = 10
    /// A host that cannot answer is asked again this much later.
    private static let retryInterval: TimeInterval = 60
    private static let timeout: TimeInterval = 20
    private static var hosts: [String: Host] = [:]

    static func answer(for workspace: Workspace) -> Answer {
        guard let destination = destination(of: workspace), let host = hosts[destination] else { return .pending }
        guard let sessions = host.sessions else { return host.hasFailed ? .unavailable : .pending }
        let terminals = terminals(of: workspace)
        return .sessions(sessions.filter { terminals[$0.terminal] != nil }, isCurrent: host.isCurrent)
    }

    /// The tab a running session is in.
    static func panel(ofSession id: String, in workspace: Workspace) -> UUID? {
        guard let destination = destination(of: workspace),
              let session = hosts[destination]?.sessions?.first(where: { $0.id == id }) else { return nil }
        return terminals(of: workspace)[session.terminal]
    }

    /// Where a project on a host keeps its memory, relative to the home folder there
    /// (`remoteDir` in wheelhouse/board/cmd/proj/brief.go).
    static func memoryFile(of project: String) -> String {
        ".wheelhouse/memory/\(project).md"
    }

    /// The project's memory on the workspace's host: its path there (under `~` until the host
    /// has said where its home folder is), and the file when it exists.
    static func memory(of project: String, in workspace: Workspace) -> (path: String, file: WheelhouseRemoteFile?) {
        let relative = memoryFile(of: project)
        let host = destination(of: workspace).flatMap { hosts[$0] }
        return ((host?.home ?? "~") + "/" + relative, host?.files[relative])
    }

    /// The user's home folder on the workspace's host, once the host has answered.
    static func home(for workspace: Workspace) -> String? {
        destination(of: workspace).flatMap { hosts[$0]?.home }
    }

    /// Whether the workspace's host has never answered and has stopped being asked often.
    static func isUnreachable(_ workspace: Workspace) -> Bool {
        guard let destination = destination(of: workspace), let host = hosts[destination] else { return false }
        return host.hasFailed && host.sessions == nil
    }

    /// Opens a new terminal on the workspace's host running `arguments`, next to one of the
    /// workspace's own there. A host's terminal takes its command when it is created, so
    /// typing into a new tab is not a way in. Returns false when the workspace has no
    /// terminal on its host, and gives `opened` the new tab once it is known.
    @discardableResult
    static func openTerminal(
        in workspace: Workspace, running arguments: [String], opened: ((UUID) -> Void)? = nil
    ) -> Bool {
        let focused = workspace.focusedPanelId.map { [$0] } ?? []
        for panel in focused + workspace.panels.keys.sorted(by: { $0.uuidString < $1.uuidString }) {
            guard let source = workspace.cloudTerminalSourcePlacement(forPanel: panel), source.machine.isSSH,
                  let pane = workspace.paneId(forPanelId: panel) else { continue }
            let outcome = workspace.routeCloudPaneTerminalCreate(
                source: source, sourcePanelID: panel,
                destination: .tab(workspaceID: workspace.id, paneID: pane.id.uuidString, index: nil), focus: true,
                commandOverride: arguments)
            if case .created(let terminal) = outcome { opened?(terminal.id) }
            return true
        }
        return false
    }

    /// Writes a project's brief on the workspace's host at `path`, and its memory at `memory`
    /// from `template` when there is none, and asks the host again soon. Both paths are
    /// absolute. False when the host could not be written to.
    static func copy(brief: Data, to path: String, memory: String, template: Data, in workspace: Workspace) async -> Bool {
        guard let destination = destination(of: workspace), path.hasPrefix("/"), memory.hasPrefix("/") else { return false }
        let word = WheelhouseRemoteSessionProbe.shellWord
        let folder = { (file: String) in word((file as NSString).deletingLastPathComponent) }
        // Through /bin/sh, whatever the user's login shell is; the files travel base64-encoded.
        let script = "set -e; umask 077; mkdir -p -- \(folder(path)) \(folder(memory)); "
            + "printf %s \(brief.base64EncodedString()) | base64 -d > \(word(path)); "
            + "[ -e \(word(memory)) ] || printf %s \(template.base64EncodedString()) | base64 -d > \(word(memory))"
        let connection = FilePreviewRemoteFolders.connection(to: destination, from: workspace)
        guard await run(connection, "exec /bin/sh -c " + word(script)) != nil else { return false }
        hosts[destination]?.askedAt = .distantPast
        return true
    }

    /// Asks the hosts of `workspaces` that are due.
    static func refresh(workspaces: [Workspace], harnesses: [WheelhouseHarness]) {
        // Each host is also asked about the memories of its projects.
        var files: [String: [String]] = [:]
        for workspace in workspaces {
            guard let destination = destination(of: workspace), let project = WheelhouseSessions.project(of: workspace)
            else { continue }
            files[destination, default: []].append(memoryFile(of: project))
        }
        var connected: Set<String> = []
        for workspace in workspaces {
            guard let destination = destination(of: workspace), connected.insert(destination).inserted else { continue }
            var host = hosts[destination] ?? Host()
            let wait = host.hasFailed && host.sessions == nil ? retryInterval : interval
            guard !host.isAsking, Date().timeIntervalSince(host.askedAt) >= wait else { continue }
            host.isAsking = true
            host.askedAt = Date()
            hosts[destination] = host
            let connection = FilePreviewRemoteFolders.connection(to: destination, from: workspace)
            let command = WheelhouseRemoteSessionProbe.command(harnesses: harnesses, files: files[destination] ?? [])
            Task { @MainActor in
                let output = await run(connection, command)
                let answer = output.flatMap { WheelhouseRemoteSessionProbe.answer(inOutput: $0, harnesses: harnesses) }
                var host = hosts[destination] ?? Host()
                host.isAsking = false
                host.isCurrent = answer != nil
                host.hasFailed = answer == nil
                if let answer {
                    host.sessions = answer.sessions
                    host.home = answer.home ?? host.home
                    host.files = answer.files
                }
                hosts[destination] = host
            }
        }
        // A host nothing is connected to any more is asked afresh the next time.
        hosts = hosts.filter { connected.contains($0.key) || $0.value.isAsking }
    }

    private static func destination(of workspace: Workspace) -> String? {
        guard let configuration = workspace.remoteConfiguration, configuration.transport == .ssh else { return nil }
        return configuration.destination
    }

    /// The host's id of each terminal in the workspace, with the tab that shows it.
    private static func terminals(of workspace: Workspace) -> [String: UUID] {
        var found: [String: UUID] = [:]
        for panel in workspace.panels.keys {
            guard let resource = SurfaceCatalog.shared.projectionIncludingPendingRestore(forPanel: panel)?.resource,
                  resource.kind == .terminal else { continue }
            found[resource.key] = panel
        }
        return found
    }

    /// What the probe printed on the host; nil when it could not be run there in time.
    private static func run(_ connection: CodeEditorRemoteHost, _ command: String) async -> Data? {
        await withCheckedContinuation { continuation in
            DispatchQueue.global(qos: .utility).async {
                let process = Process()
                let output = Pipe()
                process.executableURL = URL(fileURLWithPath: "/usr/bin/ssh")
                process.arguments = connection.sshArguments + [command]
                if let environment = connection.environment { process.environment = environment }
                process.standardInput = FileHandle.nullDevice
                process.standardOutput = output
                process.standardError = FileHandle.nullDevice
                do {
                    try process.run()
                } catch {
                    continuation.resume(returning: nil)
                    return
                }
                let deadline = DispatchWorkItem { if process.isRunning { process.terminate() } }
                DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + timeout, execute: deadline)
                let data = output.fileHandleForReading.readDataToEndOfFile()
                process.waitUntilExit()
                deadline.cancel()
                continuation.resume(returning: process.terminationStatus == 0 ? data : nil)
            }
        }
    }
}

/// The agent sessions of a terminal, found from its processes and the harness list
/// (`WheelhouseHarness.builtIn` and `<home>/harnesses.json`).
@MainActor
enum WheelhouseHarnessScan {
    struct Session {
        let id: String
        let harness: WheelhouseHarness
        let directory: String?
        let title: String?
        let transcript: String?
    }

    private struct Known {
        var id: String?
        var file: String?
        var transcript: String?
        var title: String?
        var lookedAt = Date.distantPast
    }

    private static var harnesses = WheelhouseHarness.builtIn
    /// What was found out about a running agent, by process id and start time.
    private static var known: [String: Known] = [:]
    private static var titles: [String: String] = [:]

    static func readHarnesses(home: URL) {
        harnesses = WheelhouseHarness.all(userList: try? Data(contentsOf: home.appendingPathComponent("harnesses.json")))
    }

    static func harness(id: String) -> WheelhouseHarness? {
        harnesses.first { $0.id == id }
    }

    /// Every harness: the built-in ones and the user's list.
    static var all: [WheelhouseHarness] { harnesses }

    static func sessions(onTTY tty: String) -> [Session] {
        let agents = WheelhouseHarnessMatch.agents(in: processes(onTTY: tty), harnesses: harnesses)
        return agents.compactMap { agent in
            let key = "\(agent.process.pid)@\(Int(agent.process.startedAt))"
            var entry = known[key] ?? Known()
            // Looking a session up reads files, so it is not done on every pass.
            if entry.id == nil || entry.title == nil, Date().timeIntervalSince(entry.lookedAt) > 8 {
                entry.lookedAt = Date()
                look(up: agent, into: &entry)
                if known.count > 256 { known.removeAll() }
                known[key] = entry
            }
            guard let id = entry.id else { return nil }
            return Session(
                id: id, harness: agent.harness, directory: agent.process.directory, title: entry.title,
                transcript: entry.transcript)
        }
    }

    /// A session's first prompt from its transcript, read once it is there.
    static func title(transcript path: String?, session: String) -> String? {
        if let title = titles[session] { return title }
        guard let path, let title = firstPrompt(inFile: path) else { return nil }
        if titles.count > 512 { titles.removeAll() }
        titles[session] = title
        return title
    }

    private static func look(up agent: WheelhouseHarnessAgent, into entry: inout Known) {
        let program = agent.program
        let process = agent.process
        if entry.id == nil, let template = program.pidFile {
            let path = expand(template.replacingOccurrences(of: "{pid}", with: String(process.pid)))
            if let data = FileManager.default.contents(atPath: path),
               let object = try? JSONSerialization.jsonObject(with: data) as? [String: Any] {
                entry.id = object["sessionId"] as? String
            }
        }
        if entry.id == nil, let folder = program.sessionFiles, let directory = process.directory,
           let file = sessionFile(in: expand(folder), since: process.startedAt, directory: directory) {
            entry.id = WheelhouseHarness.sessionId(inFileName: (file as NSString).lastPathComponent)
            entry.file = file
        }
        guard entry.title == nil, let id = entry.id else { return }
        let transcript = entry.file
            ?? process.directory.flatMap { program.transcriptPath(id: id, directory: $0) }.map(expand)
        entry.transcript = transcript
        entry.title = transcript.flatMap(firstPrompt(inFile:))
    }

    /// The newest session file written since the agent started that names the agent's folder.
    private static func sessionFile(in folder: String, since start: Double, directory: String) -> String? {
        let keys: [URLResourceKey] = [.creationDateKey, .isRegularFileKey]
        guard let files = FileManager.default.enumerator(
            at: URL(fileURLWithPath: folder, isDirectory: true), includingPropertiesForKeys: keys
        ) else { return nil }
        var best: (path: String, created: Date)?
        for case let file as URL in files where ["jsonl", "json"].contains(file.pathExtension) {
            guard let values = try? file.resourceValues(forKeys: Set(keys)), values.isRegularFile == true,
                  let created = values.creationDate, created.timeIntervalSince1970 >= start - 2,
                  created > best?.created ?? .distantPast,
                  WheelhouseHarness.sessionId(inFileName: file.lastPathComponent) != nil,
                  let head = head(ofFile: file.path, bytes: 64 * 1024),
                  WheelhouseTranscript.sessionFileHead(head, isIn: directory) else { continue }
            best = (file.path, created)
        }
        return best?.path
    }

    private static func firstPrompt(inFile path: String) -> String? {
        guard let text = head(ofFile: path, bytes: 1024 * 1024) else { return nil }
        return WheelhouseTranscript.firstPrompt(inLines: text.split(whereSeparator: \.isNewline))
    }

    private static func head(ofFile path: String, bytes: Int) -> String? {
        guard let handle = FileHandle(forReadingAtPath: path) else { return nil }
        defer { try? handle.close() }
        guard let data = try? handle.read(upToCount: bytes) else { return nil }
        return String(decoding: data, as: UTF8.self)
    }

    private static func expand(_ path: String) -> String {
        (path as NSString).expandingTildeInPath
    }

    private static func processes(onTTY tty: String) -> [WheelhouseProcess] {
        var device = stat()
        guard stat("/dev/" + tty, &device) == 0 else { return [] }
        var pids = [pid_t](repeating: 0, count: 512)
        let bytes = proc_listpids(
            UInt32(PROC_TTY_ONLY), UInt32(bitPattern: device.st_rdev), &pids,
            Int32(pids.count * MemoryLayout<pid_t>.size))
        guard bytes > 0 else { return [] }
        return pids.prefix(Int(bytes) / MemoryLayout<pid_t>.size).filter { $0 > 0 }.compactMap(process)
    }

    private static func process(_ pid: pid_t) -> WheelhouseProcess? {
        var info = proc_bsdinfo()
        let size = Int32(MemoryLayout<proc_bsdinfo>.size)
        guard proc_pidinfo(pid, PROC_PIDTBSDINFO, 0, &info, size) == size else { return nil }
        var path = [CChar](repeating: 0, count: 4 * Int(MAXPATHLEN))
        let name = proc_pidpath(pid, &path, UInt32(path.count)) > 0
            ? (String(cString: path) as NSString).lastPathComponent
            : withUnsafeBytes(of: &info.pbi_comm) { String(decoding: $0.prefix { $0 != 0 }, as: UTF8.self) }
        var vnode = proc_vnodepathinfo()
        var directory: String?
        if proc_pidinfo(pid, PROC_PIDVNODEPATHINFO, 0, &vnode, Int32(MemoryLayout<proc_vnodepathinfo>.size)) > 0 {
            directory = withUnsafeBytes(of: &vnode.pvi_cdir.vip_path) { String(decoding: $0.prefix { $0 != 0 }, as: UTF8.self) }
        }
        return WheelhouseProcess(
            pid: Int(pid), parent: Int(info.pbi_ppid), name: name, arguments: commandLineStart(pid),
            startedAt: Double(info.pbi_start_tvsec), directory: directory?.isEmpty == false ? directory : nil)
    }

    /// The name a process was called by and its first argument. The rest of a command line
    /// can hold credentials and is not read out.
    private static func commandLineStart(_ pid: pid_t) -> [String] {
        var name: [Int32] = [CTL_KERN, KERN_PROCARGS2, pid]
        var size = 0
        guard sysctl(&name, 3, nil, &size, nil, 0) == 0, size > MemoryLayout<Int32>.size else { return [] }
        var buffer = [UInt8](repeating: 0, count: size)
        guard sysctl(&name, 3, &buffer, &size, nil, 0) == 0, size > MemoryLayout<Int32>.size else { return [] }
        let count = Int(buffer.withUnsafeBytes { $0.loadUnaligned(as: Int32.self) })
        var index = MemoryLayout<Int32>.size
        while index < size, buffer[index] != 0 { index += 1 }
        while index < size, buffer[index] == 0 { index += 1 }
        var arguments: [String] = []
        while arguments.count < min(count, 2), index < size {
            let start = index
            while index < size, buffer[index] != 0 { index += 1 }
            arguments.append(String(decoding: buffer[start..<index], as: UTF8.self))
            index += 1
        }
        return arguments
    }
}

extension TerminalController {
    /// The project workspace a `wheelhouse.agent.*` call means: `workspace_id`, else the selected one.
    @MainActor
    func v2WheelhouseProjectWorkspace(params: [String: Any]) -> Workspace? {
        guard let tabManager = v2ResolveTabManager(params: params),
              let workspace = v2ResolveWorkspace(params: params, tabManager: tabManager),
              WheelhouseSessions.project(of: workspace) != nil else { return nil }
        return workspace
    }

    /// `wheelhouse.agent.start`: starts the project's own agent (`role` = `project`, the default)
    /// or another agent (`agent`) on `harness`, or on the project's harness without one. With
    /// `update`, a running project agent is asked to bring the memory up to date. The harness
    /// is named by its id and its command comes from the harness list, so no command is taken
    /// from the caller.
    @MainActor
    func v2WheelhouseAgentStart(params: [String: Any]) -> V2CallResult {
        guard let workspace = v2WheelhouseProjectWorkspace(params: params) else {
            return .err(code: "not_found", message: "that workspace is not a project", data: nil)
        }
        let role = (params["role"] as? String).flatMap { $0.isEmpty ? nil : $0 } ?? WheelhouseProjectAgents.Role.project.rawValue
        guard let role = WheelhouseProjectAgents.Role(rawValue: role) else {
            return .err(code: "invalid_params", message: "role must be project or agent", data: nil)
        }
        let harness = (params["harness"] as? String).flatMap { $0.isEmpty ? nil : $0 }
        if let harness, !WheelhouseHarnessScan.all.contains(where: { $0.id == harness && $0.start != nil }) {
            return .err(code: "invalid_params", message: "no harness \(harness) with a start command", data: nil)
        }
        if let refusal = WheelhouseProjectAgents.start(
            in: workspace, role: role, harness: harness, update: v2Bool(params, "update") ?? false
        ) {
            return .err(code: "unavailable", message: refusal, data: nil)
        }
        return .ok(["started": true, "role": role.rawValue])
    }
